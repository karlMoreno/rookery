#!/usr/bin/env bash
# Prepares a fresh checkout or T3 worktree so `cargo build` works immediately.
# T3 runs this on worktree creation (see t3.json); it is safe to re-run.
#
# Why it exists: T3 worktree threads may start in a shell that never sourced
# ~/.zprofile, so they would not see MUJOCO_DIR / LIBCLANG_PATH. Writing them
# into .cargo/config.toml makes every cargo invocation in this checkout find
# them regardless of the shell. The shared target dir means five worktrees
# cost one MuJoCo + mlua build, and Cargo's lock on it serialises concurrent
# Rust builds on the Air.
#
#   worktree A ─┐
#   worktree B ─┼──▶ ~/.cache/rookery-target   (one shared CARGO_TARGET_DIR)
#   worktree C ─┘         ~/.mujoco            (one MuJoCo install)
set -euo pipefail

root="$(git rev-parse --show-toplevel)"
cd "$root"

export PATH="/opt/homebrew/opt/rustup/bin:$HOME/.cargo/bin:/opt/homebrew/bin:$PATH"

target_dir="${CARGO_TARGET_DIR:-$HOME/.cache/rookery-target}"
mujoco_dir="${MUJOCO_DIR:-$HOME/.mujoco}"
if [[ -z "${LIBCLANG_PATH:-}" ]] && command -v brew >/dev/null; then
  LIBCLANG_PATH="$(brew --prefix llvm)/lib"
fi
export CARGO_TARGET_DIR="$target_dir"

[[ -d "$mujoco_dir" ]] || echo "warning: MUJOCO_DIR $mujoco_dir does not exist" >&2

mkdir -p .cargo "$target_dir"
{
  echo "# Generated by scripts/worktree-setup.sh; gitignored, machine-specific."
  echo "[build]"
  echo "target-dir = \"$target_dir\""
  echo
  echo "[env]"
  echo "MUJOCO_DIR = \"$mujoco_dir\""
  [[ -n "${LIBCLANG_PATH:-}" ]] && echo "LIBCLANG_PATH = \"$LIBCLANG_PATH\""
} > .cargo/config.toml

(cd scene && uv sync --frozen --quiet)
cargo build --workspace --quiet
echo "worktree ready: target=$target_dir mujoco=$mujoco_dir"
