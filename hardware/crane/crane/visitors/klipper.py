"""KlipperVisitor: printer.cfg generated from the same spec as the CAD.

Pattern: Visitor. It collects every non-locked joint from the tree and every
endstop from the registry, then writes one [stepper_*] section per joint.
Why: Klipper's soft limits (position_min/max) and homing positions come from
the exact numbers MuJoCo uses, in the same world frame (mm), so the real crane
and the simulated one can't disagree about where a cell is.

Axis mapping: Klipper X = arm_x, Y = rail_y, Z = mast_z (cartesian kinematics).

The SKR Pico pin names below follow BTT's published sample config for that
board. Check them against the current sample before powering anything.
"""
from __future__ import annotations

from pathlib import Path

from crane.registry import MountRegistry
from crane.spec import FORK_RATIO, CraneSpec
from crane.tree import BodyNode, Joint, Visitor

# SKR Pico pins (from BTT's sample printer.cfg; verify before use)
PINS = {
    "x": dict(step="gpio11", dir="gpio10", enable="!gpio12", endstop="^gpio4", uart_address=0),
    "y": dict(step="gpio6", dir="gpio5", enable="!gpio7", endstop="^gpio3", uart_address=2),
    "z": dict(step="gpio19", dir="gpio28", enable="!gpio2", endstop="^gpio25", uart_address=1),
}
KLIPPER_AXIS = {"arm_x": "x", "rail_y": "y", "mast_z": "z"}


class KlipperVisitor(Visitor):
    def __init__(self, spec: CraneSpec, registry: MountRegistry):
        self.s = spec
        self.reg = registry
        self.joints: dict[str, Joint] = {}

    def enter_body(self, node: BodyNode) -> bool:
        if node.joint is not None and node.joint.driven:
            self.joints[node.joint.name] = node.joint
        return True

    def text(self) -> str:
        s = self.s
        belt_rd = 2 * s.belt_pulley_teeth                     # GT2: 2 mm pitch x teeth
        # The X pinion drives the fork's middle stage; the 2:1 belts move the
        # hook twice as far, so one motor turn is 2 x belt_rd of hook travel.
        rot = {"arm_x": belt_rd * FORK_RATIO, "rail_y": belt_rd, "mast_z": s.lead_screw_lead_mm}
        home_names = {"arm_x": "x_home", "rail_y": "y_home", "mast_z": "z_home"}
        out = [
            "# printer.cfg for the Rookery stacker crane. GENERATED by `python -m crane build`;",
            "# edit crane.toml, not this file. Coordinates are world mm, the same frame as MuJoCo:",
            "# X = arm_x (into the rack), Y = rail_y (along the aisle), Z = mast_z (hook cup height).",
            "# Pins follow BTT's SKR Pico sample config: check them before powering anything.",
            "",
            "[mcu]",
            "serial: /dev/serial/by-id/usb-Klipper_rp2040_REPLACE_ME",
            "",
            "[printer]",
            "kinematics: cartesian",
            f"max_velocity: {max(s.vmax_rail, s.vmax_arm) * 1000:.0f}",
            "max_accel: 800",
            f"max_z_velocity: {s.vmax_mast * 1000:.0f}",
            "max_z_accel: 200",
            "",
        ]
        for name in ("arm_x", "rail_y", "mast_z"):
            j = self.joints[name]
            ax = KLIPPER_AXIS[name]
            p = PINS[ax]
            lo, hi = (v * 1000 for v in j.range)
            sw = self.reg[home_names[name]]
            out += [
                f"[stepper_{ax}]   # {name}: home switch '{sw.name}' at its minimum",
                f"step_pin: {p['step']}",
                f"dir_pin: {p['dir']}",
                f"enable_pin: {p['enable']}",
                f"microsteps: {s.microsteps}",
                f"rotation_distance: {rot[name]:g}",
                f"endstop_pin: {p['endstop']}",
                f"position_endstop: {lo:.2f}",
                f"position_min: {lo:.2f}",
                f"position_max: {hi:.2f}",
                f"homing_speed: {min(j.vmax * 1000 / 4, 25):.0f}",
                "",
                f"[tmc2209 stepper_{ax}]",
                "uart_pin: gpio9",
                "tx_pin: gpio8",
                f"uart_address: {p['uart_address']}",
                f"run_current: {0.6 if name == 'arm_x' else 0.9}",
                "stealthchop_threshold: 999999",
                "",
            ]
        h = s.home
        out += [
            "[homing_override]",
            "# Home the arm first so the hook is out of the rack before anything else moves.",
            "gcode:",
            "  G28 X",
            "  G28 Z",
            "  G28 Y",
            f"  G1 Z{h['mast_z'] * 1000:.2f} F{s.vmax_mast * 60000:.0f}",
            "",
            "[gcode_macro CARRY_INTERLOCK]",
            "# Rookery Phase 6.3: no rail (Y) motion unless the arm is retracted.",
            "# Call it before every Y move (Rookery's KlipperPlant should do this).",
            "gcode:",
            f"  {{% if printer.toolhead.position.x > {h['arm_x'] * 1000 + 1:.2f} %}}",
            "    { action_raise_error(\"Arm extended: retract X before moving Y\") }",
            "  {% endif %}",
            "",
        ]
        return "\n".join(out)

    def write(self, path: Path) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.text())
        return path
